export function getCategoryBySlug(slug) {
  if (!slug) return null;
  const s = String(slug).toLowerCase().trim().replace(/[\s_]+/g, '-');
  return CATEGORIES.find(c => {
    const cSlug = c.slug.toLowerCase();
    const cId = c.id.toLowerCase();
    return cSlug === s ||
      cId === s ||
      (s === 'lifestyle-essentials' && cId === 'lifestyle') ||
      (s === 'lifestyle' && cSlug === 'lifestyle-essentials') ||
      (s === 'audio-headphones' && cId === 'audio') ||
      (s === 'sneakers-footwear' && cId === 'footwear') ||
      (s === 'watches-accessories' && cId === 'watches') ||
      (s === 'home-living' && (cId === 'home-living' || cId === 'home')) ||
      (s === 'bags-travel' && (cId === 'bags-travel' || cId === 'travel'));
  }) || null;
}

export function getCategoryById(id) {
  if (!id) return null;
  const i = String(id).toLowerCase().trim().replace(/[\s_]+/g, '-');
  return CATEGORIES.find(c => c.id.toLowerCase() === i || c.slug.toLowerCase() === i) || null;
}

export function getAllCategories() {
  return CATEGORIES;
}
