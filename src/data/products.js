// Helper query utilities
export function getProductById(idOrSlug) {
  if (!idOrSlug) return null;
  const target = String(idOrSlug).toLowerCase();
  return PRODUCTS.find(p => p.id.toLowerCase() === target || p.slug.toLowerCase() === target) || null;
}

export function getProductsByCategory(catIdOrSlug) {
  if (!catIdOrSlug || catIdOrSlug === 'all') return PRODUCTS;
  const target = String(catIdOrSlug).toLowerCase();
  return PRODUCTS.filter(p => p.category.toLowerCase() === target);
}

export function getRelatedProducts(product, limit = 4) {
  if (!product) return [];
  if (product.relatedIds && product.relatedIds.length > 0) {
    const list = product.relatedIds
      .map(id => PRODUCTS.find(p => p.id === id))
      .filter(Boolean);
    if (list.length >= limit) return list.slice(0, limit);
    const others = PRODUCTS.filter(p => p.id !== product.id && p.category === product.category && !product.relatedIds.includes(p.id));
    return [...list, ...others].slice(0, limit);
  }
  return PRODUCTS.filter(p => p.id !== product.id && p.category === product.category).slice(0, limit);
}

export function getBestsellers(limit = 8) {
  const filtered = PRODUCTS.filter(p => p.isBestseller || p.rating >= 4.8);
  return filtered.slice(0, limit);
}

export function getTrendingProducts(limit = 6) {
  const filtered = PRODUCTS.filter(p => p.isTrending || p.rating >= 4.8);
  return filtered.slice(0, limit);
}

export function getNewArrivals(limit = 8) {
  const filtered = PRODUCTS.filter(p => p.isNew);
  return filtered.slice(0, limit);
}
